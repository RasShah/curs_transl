"""AST to explicit Python expressions. String literals are escaped with repr."""
from importlib.resources import files
from .diagnostics import fail
from .limits import MAX_GENERATED_BYTES
from .nodes import Binary, Call, Literal, Range, Reference, Unary
from .semantic import addresses


def emit_expression(node):
    location = f"{node.pos.line}, {node.pos.column}"
    if isinstance(node, Literal):
        return repr(node.value)
    if isinstance(node, Reference):
        return f"_cells[{node.name!r}]"
    if isinstance(node, Range):
        return "[" + ", ".join(f"_cells[{name!r}]" for name in addresses(node)) + "]"
    if isinstance(node, Unary):
        return f"_unary({node.operator!r}, {emit_expression(node.operand)}, {location})"
    if isinstance(node, Binary):
        return (f"_binary({node.operator!r}, {emit_expression(node.left)}, "
                f"{emit_expression(node.right)}, {location})")
    if isinstance(node, Call):
        if node.name == "IF":
            condition, yes, no = node.arguments
            return (f"({emit_expression(yes)} if {emit_expression(condition)} "
                    f"else {emit_expression(no)})")
        arguments = ["*" + emit_expression(a) if isinstance(a, Range)
                     else emit_expression(a) for a in node.arguments]
        return f"_aggregate({node.name!r}, [{', '.join(arguments)}], {location})"
    raise AssertionError(type(node))


def generate(source, analysis, source_path=None):
    runtime = files("spreadsheet_lang").joinpath("runtime.py").read_text(encoding="utf-8")
    lines = ["#!/usr/bin/env python3", "# -*- coding: utf-8 -*-",
             "# Generated by TableScript 1.0.0. Requires Python 3.10+ and its standard library.",
             runtime, "", f"_SOURCE_NAME = {source.filename!r}", "", "def compute():", "    _cells = {}"]
    byte_count = sum(len(line.encode("utf-8")) + 1 for line in lines)
    for name in analysis.order:
        assignment = analysis.definitions[name]
        p = assignment.expression.pos
        expression = emit_expression(assignment.expression)
        line = f"    _cells[{name!r}] = _cell({name!r}, {p.line}, {p.column}, lambda: {expression})"
        byte_count += len(line.encode("utf-8")) + 1
        if byte_count > MAX_GENERATED_BYTES - 2048:
            fail(source, p, "ошибка генерации", "E_LIMIT", "Размер Python-программы превышает 32 МиБ.")
        lines.append(line)
    lines.extend(["    return _cells", "", "", "def main():", "    _configure_streams()", "    try:",
                  "        cells = compute()"])
    p = analysis.export.pos
    lines.extend([f"        destination = _write_csv(cells, {analysis.rows}, {analysis.columns}, "
                  f"{analysis.export.path!r}, {p.line}, {p.column}, {source_path!r})",
                  '        print(f"Сохранено: {destination}")', "        return 0",
                  "    except _TableFailure as exc:",
                  '        print(f"{_SOURCE_NAME}:{exc.line}:{exc.column}: ошибка выполнения: {exc.message}", file=sys.stderr)',
                  "        return 1", "", "", 'if __name__ == "__main__":',
                  "    raise SystemExit(main())", ""])
    result = "\n".join(lines)
    if len(result.encode("utf-8")) > MAX_GENERATED_BYTES:
        fail(source, analysis.export.pos, "ошибка генерации", "E_LIMIT",
             "Размер Python-программы превышает 32 МиБ.")
    return result
